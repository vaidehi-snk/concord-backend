const PDFDocument = require('pdfkit');

/**
 * Credit note request / debit note PDF for a dispute, in the shape an Indian
 * accounts team expects: references to the original invoice and PO, the
 * itemised reasons with their calculation, and the amount split into taxable
 * value and GST (so the vendor can issue the matching GST credit note, and
 * the buyer can reverse the right ITC).
 *
 * PDFKit's built-in fonts have no ₹ glyph, so amounts print as "Rs.".
 */
const money = (n) => `Rs. ${(Math.round((n || 0) * 100) / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const safe = (s) => String(s ?? '').replace(/₹\s?/g, 'Rs. ').replace(/[−–]/g, '-').replace(/×/g, 'x');

function generateCreditNotePDF(dispute) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const ref = `DN-${(dispute.reference || dispute._id.toString().slice(-6)).replace(/\W/g, '')}`;
    const date = new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });
    const company = dispute.company || {};
    const vendor = dispute.vendor || {};
    const inv = dispute.invoice?.extracted || {};
    const taxPct = inv.taxPercent || 0;
    const amountIncl = dispute.recoveredAmount > 0 && dispute.status === 'resolved' ? dispute.recoveredAmount : dispute.totalFinancialImpact;
    const taxable = taxPct ? amountIncl / (1 + taxPct / 100) : amountIncl;
    const gst = amountIncl - taxable;

    // header band
    doc.rect(0, 0, 595, 8).fill('#2F45C5');
    doc.fillColor('#1B2440').font('Helvetica-Bold').fontSize(20).text('DEBIT NOTE / CREDIT NOTE REQUEST', 50, 40);
    doc.font('Helvetica').fontSize(9).fillColor('#5A6275').text('Raised against supplier invoice discrepancies identified by 3-way matching', 50, 66);

    doc.fillColor('#1B2440').fontSize(10);
    const meta = [
      ['Document no.', ref],
      ['Date', date],
      ['Dispute reference', dispute.reference || dispute._id.toString()],
      ['Against invoice', dispute.invoice?.docNumber || '-'],
      ['Purchase order', dispute.po?.docNumber || '-'],
      ['Delivery challan', dispute.deliveryNote?.docNumber || '-'],
    ];
    let y = 96;
    meta.forEach(([k, v]) => {
      doc.font('Helvetica-Bold').text(k, 50, y, { width: 120 });
      doc.font('Helvetica').text(safe(v), 170, y);
      y += 15;
    });

    // parties
    doc.font('Helvetica-Bold').text('Issued by (buyer)', 330, 96);
    doc.font('Helvetica').text(safe(company.name || 'Buyer'), 330, 111, { width: 215 });
    if (company.gstin) doc.text(`GSTIN: ${company.gstin}`, 330, 125);
    doc.font('Helvetica-Bold').text('To (supplier)', 330, 146);
    doc.font('Helvetica').text(safe(vendor.name || 'Supplier'), 330, 161, { width: 215 });
    if (vendor.gstin || inv.vendorGstin) doc.text(`GSTIN: ${vendor.gstin || inv.vendorGstin}`, 330, 175);

    // reasons table
    y = 200;
    doc.moveTo(50, y).lineTo(545, y).strokeColor('#D5D9E2').stroke();
    y += 10;
    doc.font('Helvetica-Bold').fontSize(9).text('#', 50, y).text('Reason and calculation', 70, y).text('Amount', 455, y, { width: 90, align: 'right' });
    y += 16;
    doc.font('Helvetica').fontSize(9);
    dispute.flags.forEach((f, i) => {
      const text = safe(f.description) + (f.formula ? `\n${safe(f.formula)}` : '');
      const h = doc.heightOfString(text, { width: 370 });
      doc.fillColor('#1B2440').text(String(i + 1), 50, y).text(text, 70, y, { width: 370 });
      doc.text(f.financialImpact ? money(f.financialImpact) : '-', 455, y, { width: 90, align: 'right' });
      y += h + 10;
      if (y > 700) {
        doc.addPage();
        y = 60;
      }
    });
    doc.moveTo(50, y).lineTo(545, y).strokeColor('#D5D9E2').stroke();
    y += 12;

    const totals = [
      ['Taxable value', money(taxable)],
      [taxPct ? `GST @ ${taxPct}%` : 'GST', money(gst)],
      ['Total to be credited', money(amountIncl)],
    ];
    totals.forEach(([k, v], i) => {
      doc.font(i === 2 ? 'Helvetica-Bold' : 'Helvetica').fontSize(i === 2 ? 11 : 9.5);
      doc.text(k, 300, y, { width: 150, align: 'right' }).text(v, 455, y, { width: 90, align: 'right' });
      y += i === 2 ? 20 : 15;
    });

    y += 20;
    doc.font('Helvetica').fontSize(8.5).fillColor('#5A6275').text(
      'Please issue a GST credit note for the above amount against the referenced invoice (or a revised invoice), so that input tax credit can be adjusted correctly. ' +
        'Payment of the undisputed balance will be released on receipt. Every figure above is traceable to the purchase order, delivery challan and invoice listed, and to the audit trail for this dispute.',
      50,
      y,
      { width: 495 }
    );
    doc.fontSize(8).text(`Generated by Concord on ${date}.`, 50, 790);
    doc.end();
  });
}

module.exports = { generateCreditNotePDF };
